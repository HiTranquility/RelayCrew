export type Translator = (message: string, ...values: unknown[]) => string;
export function translator(language: Language): Translator {
  return (message, ...values) => {
    const template = language === 'vi' && Object.hasOwn(vietnamese, message) ? vietnamese[message] : message;
    return template.replace(/\{(\d+)\}/g, (placeholder, index) => Number(index) < values.length ? String(values[Number(index)]) : placeholder);
  };
}

